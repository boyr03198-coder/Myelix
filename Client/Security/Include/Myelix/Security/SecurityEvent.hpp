#pragma once

#include <cstdint>

namespace Myelix::Security
{

    enum class SecurityEvent : std::uint16_t
    {
        // ---------------------------------------------------------------------
        // Application
        // ---------------------------------------------------------------------

        ApplicationStarted,
        ApplicationStopped,

        // ---------------------------------------------------------------------
        // Integrity
        // ---------------------------------------------------------------------

        IntegrityCheckStarted,
        IntegrityCheckPassed,
        IntegrityCheckFailed,

        // ---------------------------------------------------------------------
        // Runtime
        // ---------------------------------------------------------------------

        DebuggerDetected,
        HookDetected,
        TamperingDetected,

        // ---------------------------------------------------------------------
        // Configuration
        // ---------------------------------------------------------------------

        ConfigurationLoaded,
        ConfigurationModified,
        ConfigurationRejected,

        // ---------------------------------------------------------------------
        // Plugins
        // ---------------------------------------------------------------------

        PluginLoaded,
        PluginBlocked,
        PluginSignatureInvalid,

        // ---------------------------------------------------------------------
        // Licensing
        // ---------------------------------------------------------------------

        LicenseValidated,
        LicenseExpired,
        LicenseRejected,

        // ---------------------------------------------------------------------
        // Authentication
        // ---------------------------------------------------------------------

        AuthenticationSucceeded,
        AuthenticationFailed,

        // ---------------------------------------------------------------------
        // Authorization
        // ---------------------------------------------------------------------

        PermissionGranted,
        PermissionDenied,

        // ---------------------------------------------------------------------
        // Updates
        // ---------------------------------------------------------------------

        UpdateVerificationSucceeded,
        UpdateVerificationFailed,

        // ---------------------------------------------------------------------
        // Fallback
        // ---------------------------------------------------------------------

        Unknown
    };

} // namespace Myelix::Security
